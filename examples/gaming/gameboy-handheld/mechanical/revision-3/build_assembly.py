"""Build a candidate from revision 2 plus authoritative PCB pad coordinates."""
from pathlib import Path
import hashlib
import json
import copy

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

config = json.loads((HERE / "assembly-config.json").read_text())
interfaces = json.loads((ROOT / "design-interfaces.json").read_text())
layout = json.loads((ROOT / "pcb/carrier-layout.json").read_text())
assembly = json.loads((ROOT / "pcb/assembly-interfaces.json").read_text())
assert layout["pcb_sha256"] == assembly["pcbSha256"]
base = ROOT / "mechanical/labwired-gameboy.kcad.ts"
assert digest(base) == config["baseKernelCad"]["sourceSha256"]
header = assembly["headers"]["A1"]
module = next(c for c in layout["components"] if c["ref"] == "A1")
pins = [p for p in module["pads"] if p["number"] in header["carrierPadNumbers"]]
assert len(pins) == 40
assert all(p["drill"] == header["carrierHoleDiameterMm"] for p in pins)
def to_case(x, y):
    return [round(x - interfaces["pcb"]["width"] / 2, 6),
            round(interfaces["pcb"]["center"][1] + interfaces["pcb"]["height"] / 2 - y, 6)]
controls = {"UP":"btn-up", "DOWN":"btn-down", "LEFT":"btn-left", "RIGHT":"btn-right", "A":"btn-a", "B":"btn-b", "SELECT":"btn-select", "START":"btn-start"}
switches = []
for c in layout["components"]:
    if c["ref"].startswith("SW"):
        # The footprint origin is a pad; its body center is the mean of its pads.
        x = sum(p["x"] for p in c["pads"]) / len(c["pads"])
        y = sum(p["y"] for p in c["pads"]) / len(c["pads"])
        switches.append({"reference":c["ref"], "id":controls[c["value"]], "center":to_case(x,y)})
switches.sort(key=lambda x:x["reference"])
pin_xy = [{"number":p["number"], "at":to_case(p["x"],p["y"]), "drill":p["drill"]} for p in pins]
px = sum(p["at"][0] for p in pin_xy) / 40
py = sum(p["at"][1] for p in pin_xy) / 40
j1_spec = assembly["connectors"]["J1"]
j1_component = next(c for c in layout["components"] if c["ref"] == "J1")
assert j1_component["rotationDegrees"] == 0, "Regenerate the connector transform for a rotated footprint"
assert j1_component["side"] == "top"
j1_pin1 = next(p for p in j1_component["pads"] if p["number"] == j1_spec["pin1PadNumber"])
assert len(j1_component["pads"]) == j1_spec["positions"]
assert all(p["drill"] == j1_spec["carrierHoleDiameterMm"] for p in j1_component["pads"])
j1_low, j1_high = j1_spec["bodyBoundsFromPin1Mm"]
j1_bounds = [to_case(j1_pin1["x"] + j1_low[0], j1_pin1["y"] + j1_high[1]),
             to_case(j1_pin1["x"] + j1_high[0], j1_pin1["y"] + j1_low[1])]
j1 = {"pins": [{"number":p["number"], "at":to_case(p["x"],p["y"]), "drill":p["drill"]} for p in j1_component["pads"]],
      "bodyBoundsCaseMm": j1_bounds,
      **{k:j1_spec[k] for k in ["partNumber","matingHousing","matedHeightMm","terminalSquareMm","terminalTailLengthMm","pitchMm","carrierHoleDiameterMm","sources","drawingScope","matingLimitation"]}}
derived = {"outline":[to_case(x,y) for x,y in layout["outline"]], "pins":pin_xy,
           "switches":switches, "moduleCenter":[px,py], "header":header,
           "j1":j1, "pcbSha256":layout["pcb_sha256"]}
effective = copy.deepcopy(interfaces)
effective["speaker"]["center"] = config["speakerReservation"]["center"]
pcb_bottom = interfaces["pcb"]["center"][2] - interfaces["pcb"]["thickness"] / 2
usb_z = pcb_bottom - header["bodyHeightMm"] - config["module"]["boardThicknessMm"] - config["directUsb"]["receptacleHeightMm"] / 2
usb_interface = next(c for c in effective["connectors"] if c["id"] == "usb1")
usb_interface.update({"center":[0,interfaces["case"]["height"],round(usb_z,6)],
                      "opening":config["directUsb"]["openingMm"],
                      "note":"Direct external plug access to the rear-mounted Black Pill; module mating datum and seated shoulder offset remain explicit assumptions. This supersedes the revision-2 extension concept."})
sources = {p: digest(ROOT / p) for p in ["design-interfaces.json", "pcb/carrier-layout.json", "pcb/assembly-interfaces.json", "mechanical/labwired-gameboy.kcad.ts"]}
sources["mechanical/revision-3/assembly-config.json"] = digest(HERE / "assembly-config.json")
sources["mechanical/revision-3/assembly-body.ts"] = digest(HERE / "assembly-body.ts")
sources["mechanical/revision-3/build_assembly.py"] = digest(HERE / "build_assembly.py")
body = (HERE / "assembly-body.ts").read_text()
source = "// Candidate assembly detail. Generated by build_assembly.py. Units: mm.\n"
source += "// Vendor envelopes and assumptions are distinguished in assembly-config.json.\n"
source += "// Input SHA-256: " + json.dumps(sources,sort_keys=True) + "\n"
for name,value in [("I",effective),("P",{k:v for k,v in derived.items() if k != "outline"}),("C",config)]:
    source += "const " + name + " = " + json.dumps(value,separators=(",",":")) + ";\n"
source += body
(HERE / "labwired-gameboy-assembly.kcad.ts").write_text(source)
(HERE / "derived-interfaces.json").write_text(json.dumps({"sources":sources,"effectiveInterfaces":effective,"derived":derived},indent=2)+"\n")
print(json.dumps({"sourceSha256":hashlib.sha256(source.encode()).hexdigest(),"bytes":len(source.encode()),"pcbSha256":layout["pcb_sha256"]}))
